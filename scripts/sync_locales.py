def _load(code: str) -> dict:
    path = OUT / f"{code}.json"
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    return {str(k): str(v) for k, v in data.items() if isinstance(v, str)}


def _dump(code: str, data: dict) -> None:
    # Stable key order: follow zh-CN master order, then any extras.
    path = OUT / f"{code}.json"
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def _ordered(master_keys: list, data: dict) -> dict:
    out = {}
    for k in master_keys:
        if k in data:
            out[k] = data[k]
    for k, v in data.items():
        if k not in out:
            out[k] = v
    return out


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    zh = _load("zh-CN")
    en = _load("en-US")
    zh.update(NEW_ZH)
    en.update(NEW_EN)

    # Master key list = zh ∪ en
    master_keys = list(dict.fromkeys([*zh.keys(), *en.keys()]))
    # Ensure every master key exists in both masters
    for k in master_keys:
        if k not in zh:
            zh[k] = en.get(k, k)
        if k not in en:
            en[k] = zh.get(k, k)

    catalogs = {"zh-CN": zh, "en-US": en}
    for code in LANGS:
        if code in catalogs:
            continue
        cur = _load(code)
        for k in master_keys:
            if k in cur and cur[k]:
                continue
            if code == "zh-TW" and k in TW_OVERRIDES:
                cur[k] = TW_OVERRIDES[k]
            else:
                cur[k] = en[k]
        # Apply TW overrides even when key already exists but is Simplified leftover
        if code == "zh-TW":
            for k, v in TW_OVERRIDES.items():
                cur[k] = v
        # Deepen secondary languages beyond English fill-ins
        for k, v in SECONDARY_OVERRIDES.get(code, {}).items():
            cur[k] = v
        catalogs[code] = cur

    for code in LANGS:
        ordered = _ordered(master_keys, catalogs[code])
        _dump(code, ordered)
        print(f"wrote {code}.json ({len(ordered)} keys)")


if __name__ == "__main__":
    main()
